package com.paperdesign.shaders

import com.paperdesign.shaders.specs.ShaderCatalog
import org.junit.Assert.assertEquals
import org.junit.Test
import java.io.File

/**
 * Keeps `docs/SHADERS.md` (every shader id, parameter and preset) in sync with the specs.
 * Regenerate with `UPDATE_DOCS=1 ./gradlew :paper-shaders:testDebugUnitTest`.
 */
class ShaderReferenceDocTest {

    private val file = File("../docs/SHADERS.md")

    @Test
    fun shaderReference_isUpToDate() {
        val generated = generate()
        if (System.getenv("UPDATE_DOCS") == "1") {
            file.writeText(generated)
            return
        }
        assertEquals(
            "docs/SHADERS.md is stale. Run: UPDATE_DOCS=1 ./gradlew :paper-shaders:testDebugUnitTest",
            generated,
            file.takeIf { it.exists() }?.readText(),
        )
    }

    private fun fmt(f: Float): String = if (f == f.toLong().toFloat()) f.toLong().toString() else f.toString()

    private fun describe(p: ParamDef): String = when (p) {
        is FloatParam -> "number ${fmt(p.min)} to ${fmt(p.max)}" + if (p.step > 0f) " (step ${fmt(p.step)})" else ""
        is EnumParam -> p.options.joinToString(", ") { "`\"$it\"`" }
        is BoolParam -> "Boolean"
        is ColorParam -> "color (`ArgbColor` or `Color`)"
        is ColorsParam -> "1 to ${p.maxCount} colors"
    }

    private fun generate(): String = buildString {
        appendLine("# Shader reference")
        appendLine()
        appendLine("<!-- Generated by ShaderReferenceDocTest. Do not edit by hand. -->")
        appendLine()
        appendLine("Every shader in `ShaderCatalog.all`, with the keys `ShaderState.set` accepts. All shaders also take the")
        appendLine("common sizing params, and animated shaders take `speed` and `frame`; see [Common parameters](#common-parameters).")
        appendLine()
        appendLine("| Id | Title | Animated | Image input | Presets |")
        appendLine("|---|---|---|---|---|")
        for (s in ShaderCatalog.all) {
            appendLine("| [`${s.id}`](#${s.id}) | ${s.title} | ${if (s.animated) "yes" else "no"} | ${if (s.usesImage) "yes" else "no"} | ${s.presets.size} |")
        }
        appendLine()
        appendLine("## Common parameters")
        appendLine()
        appendLine("Presets usually set these too; the fallback column is used when a preset leaves one out.")
        appendLine()
        appendLine("| Key | Type | Fallback |")
        appendLine("|---|---|---|")
        for (p in listOf(CommonParams.speed, CommonParams.frame) + CommonParams.sizing) {
            val d = ShaderState.DEFAULTS[p.key]?.let { if (it is Float) fmt(it) else "\"$it\"" }
            appendLine("| `${p.key}` | ${describe(p)} | `$d` |")
        }
        for (s in ShaderCatalog.all) {
            appendLine()
            appendLine("## ${s.id}")
            appendLine()
            appendLine("**${s.title}**. ${s.description}")
            appendLine()
            if (s.interactionHint != null) {
                appendLine("Interactive: ${s.interactionHint}")
                appendLine()
            }
            if (s.params.isNotEmpty()) {
                appendLine("| Key | Label | Type |")
                appendLine("|---|---|---|")
                for (p in s.params) appendLine("| `${p.key}` | ${p.label} | ${describe(p)} |")
                appendLine()
            }
            appendLine("Presets: " + s.presets.joinToString(", ") { "`${it.name}`" })
        }
    }
}
